function resolveDistrictForWrappedX(mapId: MapId, groundX: number): {
  district: DistrictSegmentDef;
  wrappedX: number;
} {
  const list = MAP_DISTRICTS[mapId];
  const cycleLength = list[list.length - 1].endX;
  const wrappedX = ((groundX % cycleLength) + cycleLength) % cycleLength;
  const found = list.find((d) => wrappedX >= d.startX && wrappedX < d.endX);
  return { district: found ?? list[list.length - 1], wrappedX };
}

/**
 * Deterministically returns the permanent ShopIdentity for a given (mapId, slotIndex, side).
 * Uses wrapped city coordinates so endless loops preserve each physical location's exact shop identity.
 */
export function getPermanentShopForSlot(
  mapId: MapId,
  slotIndex: number,
  side: -1 | 1
): ShopIdentity {
  const groundX = slotIndex * BUILDING_SLOT_SPACING_X;
  const { district, wrappedX } = resolveDistrictForWrappedX(mapId, groundX);
  const bank = DISTRICT_SHOP_CATALOGUE[district.id];
  const sideList = side === -1 ? bank.left : bank.right;

  const localSlot = Math.max(0, Math.round((wrappedX - district.startX) / BUILDING_SLOT_SPACING_X));
  const blueprint = sideList[((localSlot % sideList.length) + sideList.length) % sideList.length];
  const sideTag = side === -1 ? 'L' : 'R';

  return {
    shopId: `shop_${mapId}_${district.id}_${sideTag}_${localSlot}_${blueprint.idSuffix}`,
    nameBn: blueprint.nameBn,
    nameEn: blueprint.nameEn,
    mapId,
    districtId: district.id,
    businessType: blueprint.businessType,
    side,
    slotIndex,
    groundX,
    signboard: {
      bgColor: blueprint.signBg,
      borderColor: PALETTE.ink,
      textColor: blueprint.signText,
      accentStripColor: blueprint.trimColor,
    },
    appearance: {
      wallColor: blueprint.wallColor,
      sideWallColor: blueprint.sideWallColor,
      trimColor: blueprint.trimColor,
      awningColor: blueprint.awningColor,
      roofStyle: blueprint.roofStyle,
      stories: blueprint.stories,
      hasBalcony: blueprint.hasBalcony,
      hasWaterTank: blueprint.hasWaterTank,
      isUniversityHall: Boolean(blueprint.isUniversityHall),
    },
  };
}

export function getAllConfiguredShopNames(mapId?: MapId): ShopIdentity[] {
  const mapIds: MapId[] = mapId ? [mapId] : ['dhaka', 'chattogram', 'sylhet'];
  const out: ShopIdentity[] = [];
  for (const id of mapIds) {
    const districts = MAP_DISTRICTS[id];
    const maxLen = districts[districts.length - 1].endX;
    const totalSlots = Math.floor(maxLen / BUILDING_SLOT_SPACING_X);
    for (let slotIndex = 0; slotIndex < totalSlots; slotIndex++) {
      out.push(getPermanentShopForSlot(id, slotIndex, -1));
      out.push(getPermanentShopForSlot(id, slotIndex, 1));
    }
  }
  return out;
}
